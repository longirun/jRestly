package ru.jrestly.tracing;

import java.security.SecureRandom;
import java.util.HexFormat;
import java.util.Objects;
import java.util.UUID;
import java.util.function.Supplier;
import java.util.random.RandomGenerator;

/**
 * Standard factory methods and implementations for {@link TraceIdGenerator}.
 */
public final class TraceIdGenerators {

    private static final TraceIdGenerator UUID_GENERATOR = () -> UUID.randomUUID().toString();
    private static final RandomGenerator RANDOM = new SecureRandom();
    private static final HexFormat HEX = HexFormat.of();

    private TraceIdGenerators() {
    }

    /**
     * Returns a generator producing standard UUID v4 strings (e.g. {@code "c9a646d3-9c61-4cc7-bc18-209214b7e8d1"}).
     *
     * @return the UUID v4 generator
     */
    public static TraceIdGenerator uuid() {
        return UUID_GENERATOR;
    }

    /**
     * Creates a generator producing random lowercase hexadecimal strings of the given byte length.
     * For instance, {@code hex(16)} produces 32 hex characters.
     *
     * @param byteLength the number of random bytes to generate (must be &gt; 0)
     * @return a hex generator
     * @throws IllegalArgumentException if {@code byteLength <= 0}
     */
    public static TraceIdGenerator hex(int byteLength) {
        if (byteLength <= 0) {
            throw new IllegalArgumentException("byteLength must be strictly positive: " + byteLength);
        }
        return () -> {
            byte[] bytes = new byte[byteLength];
            RANDOM.nextBytes(bytes);
            return HEX.formatHex(bytes);
        };
    }

    /**
     * Creates a generator that prepends a prefix to each ID generated by the given supplier.
     *
     * @param prefix the string prefix, not null
     * @param delegate the underlying generator, not null
     * @return a prefixed generator
     */
    public static TraceIdGenerator prefixed(String prefix, TraceIdGenerator delegate) {
        Objects.requireNonNull(prefix, "prefix must not be null");
        Objects.requireNonNull(delegate, "delegate generator must not be null");
        return () -> prefix + delegate.generate();
    }

    /**
     * Creates a generator that extracts an ID from a {@link ThreadLocal} holder if present,
     * or falls back to an alternative supplier when absent.
     *
     * @param holder the ThreadLocal storing active correlation ID, not null
     * @param fallback fallback generator if thread-local holds null or blank, not null
     * @return a context-aware generator
     */
    public static TraceIdGenerator threadLocal(ThreadLocal<String> holder, Supplier<String> fallback) {
        Objects.requireNonNull(holder, "holder must not be null");
        Objects.requireNonNull(fallback, "fallback must not be null");
        return () -> {
            String val = holder.get();
            if (val != null && !val.isBlank()) {
                return val.trim();
            }
            return fallback.get();
        };
    }
}
