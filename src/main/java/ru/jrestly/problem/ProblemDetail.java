    /**
     * Minimal, zero-dependency JSON parser for Problem Details.
     */
    private static final class ZeroDepJsonParser {

        static Map<String, Object> parseObject(String json) {
            int len = json.length();
            int i = 1; // skip '{'

            Map<String, Object> map = new LinkedHashMap<>();
            while (i < len) {
                i = skipWhitespace(json, i);
                if (i >= len) break;
                if (json.charAt(i) == '}') {
                    i++;
                    break;
                }

                if (json.charAt(i) != '"') {
                    throw new IllegalArgumentException("Expected string key at index " + i);
                }
                String key = parseString(json, i);
                i = skipQuotedString(json, i);

                i = skipWhitespace(json, i);
                if (i >= len || json.charAt(i) != ':') {
                    throw new IllegalArgumentException("Expected ':' at index " + i);
                }
                i++; // skip ':'

                i = skipWhitespace(json, i);
                ParseResult valResult = parseValue(json, i);
                map.put(key, valResult.value);
                i = valResult.nextIndex;

                i = skipWhitespace(json, i);
                if (i < len && json.charAt(i) == ',') {
                    i++;
                } else if (i < len && json.charAt(i) == '}') {
                    i++;
                    break;
                } else {
                    throw new IllegalArgumentException("Expected ',' or '}' at index " + i);
                }
            }
            return map;
        }

        private static int skipWhitespace(String s, int i) {
            int len = s.length();
            while (i < len && Character.isWhitespace(s.charAt(i))) {
                i++;
            }
            return i;
        }

        private static int skipQuotedString(String s, int start) {
            int len = s.length();
            int i = start + 1;
            while (i < len) {
                char c = s.charAt(i);
                if (c == '\\') {
                    i += 2;
                } else if (c == '"') {
                    return i + 1;
                } else {
                    i++;
                }
            }
            throw new IllegalArgumentException("Unclosed quote starting at index " + start);
        }

        private static String parseString(String s, int start) {
            StringBuilder sb = new StringBuilder();
            int len = s.length();
            int i = start + 1;
            while (i < len) {
                char c = s.charAt(i);
                if (c == '\\') {
                    i++;
                    if (i >= len) break;
                    char esc = s.charAt(i);
                    switch (esc) {
                        case '"' -> sb.append('"');
                        case '\\' -> sb.append('\\');
                        case '/' -> sb.append('/');
                        case 'b' -> sb.append('\b');
                        case 'f' -> sb.append('\f');
                        case 'n' -> sb.append('\n');
                        case 'r' -> sb.append('\r');
                        case 't' -> sb.append('\t');
                        case 'u' -> {
                            if (i + 4 >= len) {
                                throw new IllegalArgumentException("Incomplete unicode escape sequence starting at index " + (i - 1));
                            }
                            String hex = s.substring(i + 1, i + 5);
                            try {
                                sb.append((char) Integer.parseInt(hex, 16));
                            } catch (NumberFormatException e) {
                                throw new IllegalArgumentException("Invalid unicode escape sequence '\\u" + hex + "' at index " + (i - 1), e);
                            }
                            i += 4;
                        }
                        default -> sb.append(esc);
                    }
                } else if (c == '"') {
                    return sb.toString();
                } else {
                    sb.append(c);
                }
                i++;
            }
            throw new IllegalArgumentException("Unclosed string literal starting at index " + start);
        }

        private record ParseResult(Object value, int nextIndex) {
        }

        private static ParseResult parseValue(String s, int i) {
            int len = s.length();
            if (i >= len) {
                throw new IllegalArgumentException("Unexpected end of JSON at index " + i);
            }
            char c = s.charAt(i);

            if (c == '"') {
                String str = parseString(s, i);
                int next = skipQuotedString(s, i);
                return new ParseResult(str, next);
            }
            if (c == '{') {
                int end = findMatchingBracket(s, i, '{', '}');
                String sub = s.substring(i, end + 1);
                Map<String, Object> nested = parseObject(sub);
                return new ParseResult(nested, end + 1);
            }
            if (c == '[') {
                int end = findMatchingBracket(s, i, '[', ']');
                List<Object> list = parseArray(s, i);
                return new ParseResult(list, end + 1);
            }
            if (s.startsWith("true", i)) {
                return new ParseResult(Boolean.TRUE, i + 4);
            }
            if (s.startsWith("false", i)) {
                return new ParseResult(Boolean.FALSE, i + 5);
            }
            if (s.startsWith("null", i)) {
                return new ParseResult(null, i + 4);
            }

            // Number: must start with a digit or minus sign
            if (Character.isDigit(c) || c == '-') {
                int start = i;
                if (c == '-') {
                    i++;
                    if (i >= len || !Character.isDigit(s.charAt(i))) {
                        throw new IllegalArgumentException("Invalid number at index " + start);
                    }
                }
                while (i < len && (Character.isDigit(s.charAt(i)) || s.charAt(i) == '.' || s.charAt(i) == 'e' || s.charAt(i) == 'E' || s.charAt(i) == '+' || s.charAt(i) == '-')) {
                    i++;
                }
                String numStr = s.substring(start, i);
                try {
                    if (numStr.contains(".") || numStr.contains("e") || numStr.contains("E")) {
                        return new ParseResult(Double.parseDouble(numStr), i);
                    } else {
                        long l = Long.parseLong(numStr);
                        if (l >= Integer.MIN_VALUE && l <= Integer.MAX_VALUE) {
                            return new ParseResult((int) l, i);
                        }
                        return new ParseResult(l, i);
                    }
                } catch (NumberFormatException e) {
                    throw new IllegalArgumentException("Invalid number format at index " + start + ": " + numStr, e);
                }
            }

            throw new IllegalArgumentException("Unexpected token at index " + i + ": '" + c + "'");
        }

        private static List<Object> parseArray(String s, int start) {
            List<Object> list = new ArrayList<>();
            int len = s.length();
            int i = start + 1; // skip '['
            while (i < len) {
                i = skipWhitespace(s, i);
                if (i >= len) {
                    throw new IllegalArgumentException("Unclosed array starting at index " + start);
                }
                if (s.charAt(i) == ']') {
                    break;
                }

                ParseResult res = parseValue(s, i);
                list.add(res.value);
                i = res.nextIndex;

                i = skipWhitespace(s, i);
                if (i < len && s.charAt(i) == ',') {
                    i++;
                } else if (i < len && s.charAt(i) == ']') {
                    break;
                } else {
                    throw new IllegalArgumentException("Expected ',' or ']' at index " + i);
                }
            }
            return list;
        }

        private static int findMatchingBracket(String s, int start, char open, char close) {
            int depth = 0;
            boolean inQuotes = false;
            int len = s.length();
            for (int i = start; i < len; i++) {
                char c = s.charAt(i);
                if (c == '\\' && inQuotes) {
                    i++;
                    continue;
                }
                if (c == '"') {
                    inQuotes = !inQuotes;
                    continue;
                }
                if (!inQuotes) {
                    if (c == open) depth++;
                    else if (c == close) {
                        depth--;
                        if (depth == 0) return i;
                    }
                }
            }
            throw new IllegalArgumentException("Unclosed bracket '" + open + "' starting at index " + start);
        }
    }
