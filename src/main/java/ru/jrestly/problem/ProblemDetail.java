    /**
     * Serializes this Problem Detail to a compact JSON string according to RFC 9457.
     *
     * @return the JSON string
     */
    public String toJson() {
        StringBuilder sb = new StringBuilder("{");
        sb.append("\"type\":\"").append(escapeJson(type.toString())).append("\"");

        if (title != null) {
            sb.append(",\"title\":\"").append(escapeJson(title)).append("\"");
        }
        if (status > 0) {
            sb.append(",\"status\":").append(status);
        }
        if (detail != null) {
            sb.append(",\"detail\":\"").append(escapeJson(detail)).append("\"");
        }
        if (instance != null) {
            sb.append(",\"instance\":\"").append(escapeJson(instance.toString())).append("\"");
        }
        for (Map.Entry<String, Object> entry : properties.entrySet()) {
            sb.append(",\"").append(escapeJson(entry.getKey())).append("\":");
            appendJsonValue(sb, entry.getValue());
        }
        sb.append("}");
        return sb.toString();
    }

    /**
     * Parses a JSON string into a {@link ProblemDetail} using a built-in zero-dependency parser.
     *
     * <p>An optional leading UTF-8 byte-order mark (U+FEFF, RFC 8259 §8.1) is tolerated
     * and stripped — servers emitting a BOM-prefixed {@code application/problem+json}
     * body keep their structured error (Amendment #257).
     *
     * @param json the JSON string representing an RFC 7807 / RFC 9457 problem details payload
     * @return the parsed {@link ProblemDetail}
     * @throws IllegalArgumentException if the JSON is malformed
     */
    public static ProblemDetail fromJson(String json) {
        if (json == null || json.isBlank()) {
            throw new IllegalArgumentException("JSON payload must not be null or blank");
        }
        String trimmed = json.trim();
        if (trimmed.charAt(0) == '\uFEFF') {
            trimmed = trimmed.substring(1).trim(); // optional BOM prefix; whitespace may follow it
        }
        if (!trimmed.startsWith("{") || !trimmed.endsWith("}")) {
            throw new IllegalArgumentException("Problem Detail JSON must be an object starting with '{' and ending with '}'");
        }

        ProblemDetail pd = new ProblemDetail();
        Map<String, Object> parsed = ZeroDepJsonParser.parseObject(trimmed);
        for (Map.Entry<String, Object> entry : parsed.entrySet()) {
            String key = entry.getKey();
            Object val = entry.getValue();
            switch (key) {
                case "type" -> pd.setType(val != null ? val.toString() : null);
                case "title" -> pd.setTitle(val != null ? val.toString() : null);
                case "status" -> {
                    switch (val) {
                        case Number n -> pd.setStatus(n.intValue());
                        case null -> {}
                        default -> {
                            try {
                                pd.setStatus(Integer.parseInt(val.toString()));
                            } catch (NumberFormatException ignored) {
                            }
                        }
                    }
                }
                case "detail" -> pd.setDetail(val != null ? val.toString() : null);
                case "instance" -> pd.setInstance(val != null ? val.toString() : null);
                default -> pd.setProperty(key, val);
            }
        }
        return pd;
    }

    private static String defaultTitleForStatus(int status) {
        return switch (status) {
            case 400 -> "Bad Request";
            case 401 -> "Unauthorized";
            case 402 -> "Payment Required";
            case 403 -> "Forbidden";
            case 404 -> "Not Found";
            case 405 -> "Method Not Allowed";
            case 406 -> "Not Acceptable";
            case 408 -> "Request Timeout";
            case 409 -> "Conflict";
            case 410 -> "Gone";
            case 412 -> "Precondition Failed";
            case 413 -> "Content Too Large";
            case 415 -> "Unsupported Media Type";
            case 422 -> "Unprocessable Content";
            case 429 -> "Too Many Requests";
            case 500 -> "Internal Server Error";
            case 501 -> "Not Implemented";
            case 502 -> "Bad Gateway";
            case 503 -> "Service Unavailable";
            case 504 -> "Gateway Timeout";
            default -> "HTTP " + status;
        };
    }

    private static void appendJsonValue(StringBuilder sb, Object val) {
        switch (val) {
            case null -> sb.append("null");
            case String s -> sb.append("\"").append(escapeJson(s)).append("\"");
            case Number n -> sb.append(n);
            case Boolean b -> sb.append(b);
            case URI u -> sb.append("\"").append(escapeJson(u.toString())).append("\"");
            case Map<?, ?> m -> {
                sb.append("{");
                boolean first = true;
                for (Map.Entry<?, ?> e : m.entrySet()) {
                    if (!first) sb.append(",");
                    sb.append("\"").append(escapeJson(String.valueOf(e.getKey()))).append("\":");
                    appendJsonValue(sb, e.getValue());
                    first = false;
                }
                sb.append("}");
            }
            case Iterable<?> it -> {
                sb.append("[");
                boolean first = true;
                for (Object item : it) {
                    if (!first) sb.append(",");
                    appendJsonValue(sb, item);
                    first = false;
                }
                sb.append("]");
            }
            default -> {
                if (val.getClass().isArray()) {
                    sb.append("[");
                    int len = java.lang.reflect.Array.getLength(val);
                    for (int j = 0; j < len; j++) {
                        if (j > 0) sb.append(",");
                        appendJsonValue(sb, java.lang.reflect.Array.get(val, j));
                    }
                    sb.append("]");
                } else {
                    sb.append("\"").append(escapeJson(val.toString())).append("\"");
                }
            }
        }
    }

    /**
     * Escapes special JSON control characters, quotes, and backslashes in the input string.
     *
     * @param s the string to escape, or {@code null}
     * @return the escaped JSON string, or empty string if input is {@code null}
     */
    public static String escapeJson(String s) {
        if (s == null) return "";
        StringBuilder sb = new StringBuilder(s.length() + 8);
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"' -> sb.append("\\\"");
                case '\\' -> sb.append("\\\\");
                case '\b' -> sb.append("\\b");
                case '\f' -> sb.append("\\f");
                case '\n' -> sb.append("\\n");
                case '\r' -> sb.append("\\r");
                case '\t' -> sb.append("\\t");
                default -> {
                    if (c < 0x20) {
                        sb.append(String.format("\\u%04x", (int) c));
                    } else {
                        sb.append(c);
                    }
                }
            }
        }
        return sb.toString();
    }

