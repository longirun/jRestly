/**
 * Representation of an RFC 7807 and RFC 9457 "Problem Details for HTTP APIs" payload.
 *
 * <p>Problem Details provide a standardized, machine-readable format for conveying error
 * information in HTTP API responses (typically with media type {@code application/problem+json}
 * or {@code application/problem+xml}).</p>
 *
 * <p>Standard members defined by RFC 9457 §3.1:
 * <ul>
 *   <li>{@link #getType() type}: A URI reference identifying the problem type (defaults to {@code "about:blank"}).</li>
 *   <li>{@link #getTitle() title}: A short, human-readable summary of the problem type.</li>
 *   <li>{@link #getStatus() status}: The HTTP status code generated by the origin server.</li>
 *   <li>{@link #getDetail() detail}: A human-readable explanation specific to this occurrence of the problem.</li>
 *   <li>{@link #getInstance() instance}: A URI reference that identifies the specific occurrence.</li>
 * </ul>
 *
 * <p>Additional application-specific extension members are stored in {@link #getProperties()}.</p>
 *
 * <p>This class is zero-dependency and includes a built-in zero-dependency JSON parser
 * ({@link #fromJson(String)}) and serializer ({@link #toJson()}), while also integrating
 * seamlessly with external codecs such as Jackson, Gson, and Moshi.</p>
 */
